/**
 * 抽一句。
 *
 * 避開最近用過的幾句（recent），不然隨機會讓人覺得「怎麼又是這句」——
 * 真隨機在小樣本上重複得比直覺想像的頻繁很多。
 * @param {string[]} recent 最近用過的 key
 * @returns {{title:string, body:string, key:string}}
 */
export function pickLine(recent = []) {
  const seen = new Set(recent);
  const all = [];
  for (const v of VOICES) {
    v.lines.forEach((body, i) => all.push({ title: v.name, body, key: `${v.name}#${i}` }));
  }
  const fresh = all.filter((l) => !seen.has(l.key));
  const pool = fresh.length ? fresh : all;
  return pool[Math.floor(Math.random() * pool.length)];
}

export const TOTAL = VOICES.reduce((n, v) => n + v.lines.length, 0);
